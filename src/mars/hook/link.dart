import 'package:code_assets/code_assets.dart';
import 'package:hooks/hooks.dart';
import 'package:native_toolchain_x/native_toolchain_x.dart';
import 'package:record_use/record_use.dart';

import 'util.dart';

void main(List<String> arguments) async {
  await link(arguments, (input, output) async {
    if (!input.config.buildCodeAssets) return;

    final linker = CLinker.library(
      name: 'mars',
      assetName: 'src/mars_bindings_generated.dart',
      sources: input.assets.code
          .map(
            (asset) =>
                ArgumentError.checkNotNull(asset.file, 'file').toFilePath(),
          )
          .toList(),
      frameworks: frameworks,
      libraries: getSystemLibraries(input.config.code.targetOS),
    );
    await linker.run(
      input: input,
      output: output,
      linkerOptions: LinkerOptions.treeshake(
        // TODO(jni-treeshake): JNI symbols (JNI_OnLoad / JNI_OnUnload /
        // ImportLibs / Export* / Java_com_tencent_mars_*) are not part of the
        // Dart recordedUses, so the exact keep-whitelist version-script
        // generated by treeshake strips them and leaves them unexported:
        // System.loadLibrary("mars") never triggers JNI_OnLoad and static
        // Java registrations break. Two possible follow-ups:
        //  1) Support JNI treeshake: enumerate the symbols above to keep
        //     (native_toolchain_c 0.19.5 symbolsToKeep matches exact names
        //     only, no prefix wildcards), or switch to
        //     LinkerOptions.manual(gcSections: false, symbolsToKeep: null)
        //     to export all symbols (matching upstream marsstn, which has no
        //     version-script).
        //  2) Add a switch via HookInput.userDefines (e.g.
        //     userDefines['jni'] = true keeps JNI symbols, false = pure FFI
        //     treeshake) so this needs no hook-code change.
        // For now: pure FFI treeshake, JNI symbols not kept.
        symbolsToKeep: input.recordedUses?.calls.keys.cast<Method>().map(
          (e) => e.name,
        ),
      ),
    );
  });
}
